def get_activity_id(user_text):
    # Return the activity_id whose trigger phrases best match the user text.
    # Returns None if no activity matches.
    text_lower = user_text.lower()
    best_id    = None
    best_score = 0
    for act_id, meta in ACTIVITY_MAP.items():
        score = 0
        for phrase in meta["trigger"]:
            if phrase in text_lower:
                score += 1 + len(phrase) / 100  # longer phrase = more specific
        if score > best_score:
            best_score = score
            best_id    = act_id
    return best_id if best_score > 0 else None


def resolve_topic(text, language="unspecified", context_topic=None):
    # Resolve the canonical topic tag from user text.
    # Strong keywords in the current message ALWAYS take priority over context.
    # Returns (topic_tag, confidence) where confidence is "high"/"medium"/"low".
    t = text.lower()

    # 1. Check high-priority keywords first — these always override context.
    for keyword, topic in HIGH_PRIORITY.items():
        if keyword in t:
            return topic, "high"

    # 2. Standard alias matching.
    best_topic = None
    best_count = 0

    for topic, aliases in TOPIC_ALIASES.items():
        count = sum(1 for alias in aliases if alias in t)
        if count > best_count:
            best_count = count
            best_topic = topic

    if best_topic and best_count >= 2:
        return best_topic, "high"
    if best_topic and best_count == 1:
        return best_topic, "medium"

    # 3. KB alias matching.
    kb_match = _match_kb_aliases(t, language)
    if kb_match:
        return kb_match, "medium"

    # 4. Fall back to context topic only if no keywords matched at all.
    if context_topic:
        return context_topic, "low"

    return "programming_basics", "low"


def is_specific_question(text):
    # Return True if the user is asking a specific factual question
    # (who, when, where, what year) rather than a general explanation.
    t = text.lower().strip()
    specific_markers = [
        "who created", "who made", "who developed", "who is",
        "what year", "when was", "when did",
        "where was", "where did",
        "what is the size of", "what does %", "what does the ",
    ]
    return any(t.startswith(marker) or (" " + marker) in t for marker in specific_markers)


def is_overview_question(text):
    # Return True if the user is asking for a general overview ("what is X").
    t = text.lower().strip()
    overview_markers = ["what is", "what are", "tell me about", "explain"]
    return any(t.startswith(m) for m in overview_markers)


def _match_kb_aliases(text, language):
    # Search KB record aliases for a match with the user text.
    kb = get_kb()
    if kb is None:
        return None
    for record in kb:
        if language not in ("unspecified", "multiple") and record.get("language") not in (language, "shared"):
            continue
        for alias in record.get("aliases", []):
            if alias.lower() in text:
                return record["topic"]
    return None
